"""Cross-check the real packaged menu/model asset contracts, not UI mock data."""
import csv
import json
from pathlib import Path
import struct
import unittest
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]

def rows(path):
    return [row for row in csv.reader((ROOT/path).read_text().splitlines()) if row]

class MenuAssets(unittest.TestCase):
    def test_every_equipment_choice_has_real_packaged_render(self):
        characters={r[0]:r for r in rows('src/mp/apx_character_previews.csv')}
        weapons={r[0]:r for r in rows('src/mp/apx_weapon_previews.csv')}
        materials=((ROOT/'manifests/14-model-previews.csv').read_text()+(ROOT/'manifests/15-turntables.csv').read_text()).splitlines()
        for row in rows('src/mp/characterTable.csv'):
            self.assertIn(row[1],characters)
            for material in characters[row[1]][1:6]: self.assertIn('material,'+material,materials)
        for row in rows('src/mp/itemTable.csv'):
            self.assertIn(row[1],weapons)
            self.assertIn('material,'+weapons[row[1]][1],materials)
        for row in rows('src/mp/knifeTable.csv'):
            self.assertIn('material,apx_turn_knife_'+row[1],materials)
            knife={r[0]:r for r in rows('src/mp/apx_knife_previews.csv')}
            self.assertIn('material,'+knife[row[1]][1],materials)
        atlas=json.loads((ROOT/'ui/preview_atlas.json').read_text())
        for entry in json.loads((ROOT/'art/ui/models/catalog.json').read_text()):
            name=entry['name']
            if name not in atlas: continue
            with Image.open(ROOT/'art/ui/models'/(name+'.png')) as image:
                alpha=image.getchannel('A'); box=alpha.getbbox()
                self.assertIsNotNone(box,name)
                self.assertGreater(min(box[0],box[1],image.width-box[2],image.height-box[3]),0,name+' is clipped')
                header=(ROOT/'assets/images'/(name+'.iwi')).read_bytes()[:28]
                self.assertEqual(header[:6],b'IWi\x06\x0d\x01')
                self.assertEqual(struct.unpack_from('<2H',header,6),image.size)
            self.assertTrue((ROOT/'assets/materials'/name).exists())

    def test_shared_still_atlases_preserve_every_source_pixel_and_cell(self):
        lookup=json.loads((ROOT/'ui/preview_atlas.json').read_text())
        groups={}
        for name,slot in lookup.items(): groups.setdefault(slot['material'],[]).append((name,slot))
        self.assertLessEqual(len(groups),27)
        for material,entries in groups.items():
            with Image.open(ROOT/'art/ui/models/still-atlases'/(material+'.png')) as atlas:
                for name,slot in entries:
                    width,height=slot['size'];cols=2048//width;cell=slot['cell']
                    box=(cell%cols*width,cell//cols*height,(cell%cols+1)*width,(cell//cols+1)*height)
                    with Image.open(ROOT/'art/ui/models'/(name+'.png')) as source:
                        self.assertEqual(atlas.crop(box).tobytes(),source.convert('RGBA').tobytes(),name)
                    # Constant vertex colors survive native 8-bit packing.
                    encoded=round((cell+.5)/8*255)/255
                    self.assertEqual(int(encoded*8),cell)
            header=(ROOT/'assets/images'/(material+'.iwi')).read_bytes()[:28]
            self.assertEqual(header[:6],b'IWi\x06\x0d\x01')
            self.assertEqual(struct.unpack_from('<2H',header,6),(2048,2048))

    def test_client_pages_are_loaded_and_privilege_routes_are_declared(self):
        index=(ROOT/'src/ui_mp/menus.txt').read_text()
        manifest=(ROOT/'manifests/07-menus.csv').read_text()
        for path in (ROOT/'src').rglob('*.menu'):
            source=path.read_text(encoding='cp1252')
            if '// Generated by tools/generate_menus.py.' not in source: continue
            relative=path.relative_to(ROOT/'src').as_posix()
            self.assertIn('loadMenu { "'+relative+'" }',index)
            self.assertIn('menufile,'+relative,manifest)
            self.assertNotIn('openscriptmenu -1 ui:',source)
        routes={r[0]:r for r in rows('src/mp/apx_menu_routes.csv')}
        for name,row in routes.items():
            if name=='vip': self.assertEqual(row[1],'vip')
            if name=='dr_admin' or name.startswith(('apx_admin','apx_moderation','apx_confirm_admin','apx_reset')):
                self.assertEqual(row[1],'admin',name)
        spec=json.loads((ROOT/'ui/menu_catalog.json').read_text())
        families=spec['weapon_families']
        self.assertNotIn('secondary',families)
        self.assertEqual(set(families['primary']),{int(r[1]) for r in rows('src/mp/itemTable.csv') if len(r)<9 or r[8]!='0'})

    def test_rotating_atlases_are_complete_and_packaged(self):
        manifest=(ROOT/'manifests/15-turntables.csv').read_text().splitlines()
        jobs={row['key']:row for row in json.loads((ROOT/'art/ui/models/catalog.json').read_text())}
        for job in jobs.values():
            name='apx_turn_'+job['category']+'_'+str(job['id'])
            if 'material,'+name not in manifest: continue
            self.assertIn('material,'+name,manifest)
            with Image.open(ROOT/'art/ui/models/turntables'/(name+'.png')) as atlas:
                self.assertEqual(atlas.size,(2048,2048))
                tall=job['category']=='character'
                w,h,cols=(256,512,8) if tall else (512,256,4)
                for i in range(32):
                    frame=atlas.crop((i%cols*w,i//cols*h,(i%cols+1)*w,(i//cols+1)*h))
                    box=frame.getchannel('A').getbbox()
                    self.assertIsNotNone(box,name+' frame '+str(i))
                    self.assertGreater(min(box[0],box[1],w-box[2],h-box[3]),0,name+' clipped frame '+str(i))
            header=(ROOT/'assets/images'/(name+'.iwi')).read_bytes()[:28]
            self.assertEqual(header[:6],b'IWi\x06\x0d\x01')
            self.assertEqual(struct.unpack_from('<2H',header,6),(1024,1024))
            material=(ROOT/'assets/materials'/name).read_bytes()
            self.assertIn(b'apx_turntable_tall' if job['category']=='character' else b'apx_turntable_wide',material)

    def test_preview_texture_memory_stays_within_client_budget(self):
        names={row.split(',',1)[1] for path in ('14-model-previews.csv','15-turntables.csv')
               for row in (ROOT/'manifests'/path).read_text().splitlines() if row.startswith('material,')}
        size=sum((ROOT/'assets/images'/(name+'.iwi')).stat().st_size for name in names)
        self.assertLessEqual(size,512*1024**2,'Preview textures exceeded the 512 MiB runtime budget')

    def test_offline_navigation_and_popup_focus_remain_usable(self):
        main=(ROOT/'src/ui_mp/main.menu').read_text()
        self.assertNotIn('apx_preview_',main)
        self.assertIn('APX_UI_BACKDROP("apx_menu_background")',main)
        for relative in ['ui_mp/options.menu','ui_mp/scriptmenus/apx_audio.menu','ui_mp/scriptmenus/apx_graphics.menu']:
            source=(ROOT/'src'/relative).read_text()
            for chunk in source.split('menuDef')[1:]:
                if not any('name "'+name+'"' in chunk for name in ['main_options','main_controls','apx_audio_offline','apx_graphics_offline']): continue
                self.assertNotIn('scriptMenuResponse',chunk)
                for destination in ['team_select','dr_options','controls_multi','apx_audio','apx_graphics','dr_weapons','character_stuff']:
                    self.assertNotIn('open '+destination+';',chunk)
        for relative in ['ui/quit.menu','ui_mp/scriptmenus/popup_leavegame.menu','ui_mp/scriptmenus/apx_moderation.menu']:
            source=(ROOT/'src'/relative).read_text()
            for chunk in source.split('menuDef')[1:]:
                if 'popup' in chunk and 'APX_UI_BUTTON' in chunk:
                    self.assertIn('focuscolor 0.95 0.86 0.65 1',chunk)

    def test_settings_and_edit_fields_respect_native_client_contracts(self):
        # Server-only stat writes disconnect real clients, even though dedicated
        # bot tests accept the corresponding GSC setStat calls.
        for relative in ['ui_mp/options.menu','ui_mp/scriptmenus/dr_options.menu']:
            source=(ROOT/'src'/relative).read_text()
            self.assertNotIn('statset',source)
            self.assertNotIn('statGetInDvar 2400',source)
        connected=(ROOT/'src/ui_mp/scriptmenus/dr_options.menu').read_text()
        self.assertIn('ui:dr_options:pref:fov:110',connected)
        offline=(ROOT/'src/ui_mp/options.menu').read_text()
        self.assertIn('seta cg_fovScale 1.375',offline)
        for name in ['dr_weapons','apx_primary','dr_characters','dr_abilities','dr_sprays']:
            source=(ROOT/f'src/ui_mp/scriptmenus/{name}.menu').read_text()
            fields=[block.split('}',1)[0] for block in source.split('itemDef')[1:] if 'type ITEM_TYPE_EDITFIELD' in block.split('}',1)[0]]
            self.assertEqual(len(fields),2)
            for field in fields:
                # Without a caption the generic text painter echoes the dvar,
                # then the native edit painter draws the value a second time.
                self.assertIn('text " "',field)
        browser=(ROOT/'src/braxi/_menu_browser.gsc').read_text()
        self.assertNotIn('setClientDvars( "apx_catalog_',browser)

if __name__=='__main__': unittest.main()
