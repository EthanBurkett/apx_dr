def preference_button(key,stat,y,title,offline=False):
    out=text(key,180,y,212,title,.27)
    command={'fullbright':'r_fullbright','fps':'cg_drawFPS','minimal':'apx_minimal_hud','thirdperson':'cg_thirdperson'}[key]
    current=f'dvarInt("{command if offline else "apx_pref_"+key}")'
    for value,label in [(0,'Off'),(1,'On')]:
        x=398+value*106
        out+=button(key+str(value),x,y,100,label,preference_action(key,stat,value,offline),f'{current}!={value}')
        out+=locked(key+'_set'+str(value),x,y,100,label+' / SET',f'{current}=={value}')
    return out


def preference_action(key,stat,value,offline=False):
    # Slots 2400+ are server-owned. Connected menus only request validated GSC
    # writes; disconnected menus save ordinary archived renderer preferences.
    if not offline: return f'scriptMenuResponse "pref:{key}:{value}";'
    command={'fullbright':'r_fullbright','fps':'cg_drawFPS','minimal':'apx_minimal_hud','thirdperson':'cg_thirdperson'}.get(key)
    change=f'seta cg_fov 80;seta cg_fovScale {value/80:g}' if key=='fov' else f'seta {command} {value}'
    return f'execNow "{change}";'


