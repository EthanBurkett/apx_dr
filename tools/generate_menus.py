def main():
    from menu_catalog_data import build as build_catalog_data
    build_catalog_data()
    build_catalogs(); build_home(); build_progression(); build_admin(); build_main(); build_help_audio(); build_connect_quick()
    save('ui_mp/scriptmenus/dr_options.menu',settings())
    save('ui_mp/apx_controls.menu',controls())
    for path,source in MENUS.items():
        dest=ROOT/'src'/path; dest.parent.mkdir(parents=True,exist_ok=True)
        dest.write_text(source,encoding='ascii')
    # Enrich the engine table with readable spray labels for dynamic previews.
    spray_rows=catalog('sprayTable.csv')
    (ROOT/'src/mp/sprayTable.csv').write_text('\n'.join(','.join(row) for row in spray_rows)+'\n',encoding='ascii')
    server_open={'team_select','character_stuff','dr_options','quickstuff','dr_help','dr_characters','dr_weapons','dr_abilities','dr_sprays','apx_prestige','apx_prestige_confirm','apx_rewards','apx_knife','apx_gloves','dr_admin','apx_reset_confirm','vip','apx_intermission'}
    route_rows=[f'{name},{access},{i},{int(name in server_open)}' for i,(name,access) in enumerate(ROUTES.items(),1)]
    (ROOT/'src/mp/apx_menu_routes.csv').write_text('\n'.join(route_rows)+'\n',encoding='ascii')
    manifest=ROOT/'manifests/07-menus.csv'
    entries=manifest.read_text().splitlines()
    # Includes compile through parents; retire old standalone include entries.
    entries=[entry for entry in entries if entry not in ('menufile,ui_mp/dr_menu_frame.inc','menufile,ui_mp/perm_bans.inc','menufile,ui/bg.inc')]
    for path in MENUS:
        value='menufile,'+path
        if value not in entries: entries.append(value)
    # Recompile native utility pages against the ApX choice/popup wrappers.
    # Otherwise the client would keep stock precompiled copies from common_mp.
    for native in re.findall(r'loadMenu\s*\{\s*"([^"]+)"', (ROOT/'src/ui_mp/menus.txt').read_text()):
        if '/cac_' in native or '/settings_quick_' in native: continue
        entry='menufile,'+native
        if entry not in entries: entries.append(entry)
    manifest.write_text('\n'.join(entries)+'\n',encoding='ascii')
    table_manifest=ROOT/'manifests/04-tables.csv'
    entries=table_manifest.read_text().splitlines()
    if 'stringtable,mp/apx_menu_routes.csv' not in entries: entries.append('stringtable,mp/apx_menu_routes.csv')
    table_manifest.write_text('\n'.join(entries)+'\n',encoding='ascii')
    # Client pages load from the global UI index, independently of the network's
    # 32 registered server menu names. Keep the SDK utility menu index intact.
    index=ROOT/'src/ui_mp/menus.txt'
    index_source=index.read_text()
    head=index_source.rsplit('}',1)[0]
    for path in MENUS:
        statement='loadMenu { "'+path+'" }'
        if statement not in head: head+='\n\t'+statement
    index.write_text(head.rstrip()+'\n}\n',encoding='ascii')
    raw_manifest=ROOT/'manifests/11-other.csv'
    entries=raw_manifest.read_text().splitlines()
    if 'rawfile,ui_mp/menus.txt' not in entries: entries.append('rawfile,ui_mp/menus.txt')
    raw_manifest.write_text('\n'.join(entries)+'\n',encoding='ascii')
    print(f'Generated {len(MENUS)} menu files, {len(ROUTES)} routes from shared ApX components.')


if __name__=='__main__': main()
