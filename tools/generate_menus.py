def menu(name,title,body,active='team_select',onopen='',access='public',escape='close self; open team_select;',shell_on=True):
    ROUTES[name]=access
    offline=name.startswith(('main_','apx_main_')) or name in ('apx_audio_offline','apx_graphics_offline','single_popmenu')
    if offline:
        mapping={'dr_options':'apx_main_options','apx_controls':'apx_main_controls','apx_audio':'apx_audio_offline','apx_graphics':'apx_graphics_offline','team_select':'main_text','dr_help':'single_popmenu'}
        active=mapping.get(active,active)
        for source,destination in mapping.items(): body=body.replace('open '+source+';', 'open '+destination+';')
        escape='open quit_popmenu;' if name=='main_text' else 'close self;'
        body=re.sub(r'scriptMenuResponse "[^"]*";', '', body)
    response='' if offline else 'scriptMenuResponse "apx_open";'
    frame=shell(title,active,offline) if shell_on else ''
    return bridge((f'menuDef\n{{\nname {q(name)}\nrect 0 0 640 480 0 0\nfullScreen 0\n'
            f'focuscolor 0.89 0.78 0.53 1\nonOpen {{ {response} {onopen} }}\n'
            f'onEsc {{ {escape} }}\n{frame}{body}\n}}\n'),name)


def save(path, content):
    MENUS[path]='#include "ui_mp/components/shell.inc"\n// Generated by tools/generate_menus.py.\n{\n'+content+'}\n'


def catalog(table):
    rows=[row for row in csv.reader((ROOT/'src/mp'/table).read_text().splitlines()) if row and row[0].strip()]
    if table=='sprayTable.csv':
        rows=[row[:5]+['Spray '+str(int(row[1])+1),'Unlocked by level progression.'] for row in rows]
    return rows


