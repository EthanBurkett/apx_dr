"""Inventory installed usermaps and generate a bounded ApX Deathrun rotation.

Only reads local FFs/arena metadata; maps are never copied into the repository.
Large collections use short server dvars consumed by _vote_maps.gsc rather than
one oversized console command. Normal builds consume the checked-in config.
"""
import argparse
import json
from pathlib import Path
import re
import zipfile
import hashlib
from map_budget import compatible, public_report, source_signature

ROOT=Path(__file__).resolve().parents[1]
PREFIXES=('mp_dr_','mp_deathrun_','mp_drrun_')


def inspect_map(directory):
    name=directory.name.lower()
    result={'map':name,'deathrun':False,'reason':'No Deathrun prefix or arena support', 'arena_gametypes':[]}
    fastfiles=[p for p in directory.glob('*.ff') if p.stem.lower()==name and p.stat().st_size>0]
    if not re.fullmatch(r'mp_[a-z0-9_]+',name) or not fastfiles:
        result['reason']='Missing matching playable fastfile or invalid map name'
        return result
    arenas=[]
    for path in sorted(directory.glob('*.arena')):
        arenas.append(path.read_text(encoding='utf-8',errors='replace'))
    for path in sorted(directory.glob('*.iwd')):
        try:
            with zipfile.ZipFile(path) as archive:
                for entry in archive.infolist():
                    if entry.filename.lower().endswith('.arena') and entry.file_size<=256*1024:
                        arenas.append(archive.read(entry).decode('utf-8',errors='replace'))
        except zipfile.BadZipFile:
            result.setdefault('warnings',[]).append('Unreadable IWD: '+path.name)
    gametypes=set()
    for source in arenas:
        for block in re.findall(r'\{([^{}]*)\}',source):
            fields=dict((k.lower(),a or b) for k,a,b in re.findall(r'"?(\w+)"?\s+(?:"([^"]*)"|([^\s{}]+))',block))
            if fields.get('map','').lower()==name:
                gametypes.update(fields.get('type',fields.get('gametype','')).lower().split())
    result['arena_gametypes']=sorted(gametypes)
    if 'deathrun' in gametypes or name.startswith(PREFIXES):
        result.update(deathrun=True,reason='Arena declares Deathrun' if 'deathrun' in gametypes else 'Deathrun naming convention')
    return result


def chunks(names,limit=800):
    pages=[];current=''
    for name in names:
        token='map '+name
        if current and len(current)+len(token)+1>limit:
            pages.append(current);current=''
        current+=((' ' if current else '')+token)
    if current:pages.append(current)
    return pages


def rotation(names):
    pages=chunks(names)
    if not pages:raise ValueError('No installed Deathrun maps found; refusing to replace the rotation.')
    lines=['// Generated by tools/sync_map_rotation.py. Local installed Deathrun maps only.',
           '// _vote_maps.gsc reads every page for voting and sequential rotation.',
           '// Regenerate after adding/removing usermaps. Each command stays below 1024 bytes.',
           'set g_gametype "deathrun"',f'set apx_rotation_page_count "{len(pages)}"']
    lines += [f'set apx_rotation_{i} "{page}"' for i,page in enumerate(pages)]
    lines += [f'set sv_mapRotation "{pages[0]}"','set sv_mapRotationCurrent ""','']
    return '\n'.join(lines)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--usermaps',type=Path,default=ROOT.parent.parent/'usermaps')
    parser.add_argument('--asset-report',type=Path,default=ROOT/'ui/map_asset_budget.json')
    parser.add_argument('--fastfile',type=Path,help='Measured FF; required when importing a raw native audit report')
    args=parser.parse_args()
    if not args.usermaps.is_dir():parser.error('usermaps directory does not exist')
    maps=[inspect_map(p) for p in sorted(args.usermaps.iterdir(),key=lambda p:p.name.lower()) if p.is_dir()]
    if not args.asset_report.is_file():parser.error('Run audit_map_assets.py first, then pass its report with --asset-report and --fastfile')
    budget=json.loads(args.asset_report.read_text())
    limits=json.loads((ROOT/'ui/content_profile.json').read_text())['max_usage']
    if 'source_signature' not in budget:
        if not args.fastfile or hashlib.sha256(args.fastfile.read_bytes()).hexdigest()!=budget.get('mod_sha256'):
            parser.error('Raw audit report does not match --fastfile')
        budget=public_report(budget,ROOT,limits)
    if budget['source_signature']!=source_signature(ROOT):parser.error('Asset inputs changed; rerun the native map audit before changing the rotation')
    measured={row['map']:row for row in budget['maps']}
    for row in maps:
        allowed,reason=compatible(measured.get(row['map']),limits)
        row['rotation']=row['deathrun'] and allowed
        if row['deathrun']:row['asset_budget']=reason
    names=[row['map'] for row in maps if row['rotation']]
    # Familiar starting map, followed by stable alphabetical order.
    if 'mp_deathrun_supermario' in names:
        names.remove('mp_deathrun_supermario');names.insert(0,'mp_deathrun_supermario')
    (ROOT/'config/server/rotation.cfg').write_text(rotation(names),encoding='ascii')
    (ROOT/'ui/map_asset_budget.json').write_text(json.dumps(budget,indent=2)+'\n',encoding='ascii')
    report={'installed_directories':len(maps),'rotation_maps':len(names),'pages':len(chunks(names)),
            'classification':'Deathrun prefix/arena support, plus measured client-zone asset budgets and a successful native load.',
            'maps':maps}
    (ROOT/'ui/map_inventory.json').write_text(json.dumps(report,indent=2)+'\n',encoding='ascii')
    print(f'Inventoried {len(maps)} usermaps: {len(names)} Deathrun maps in {report["pages"]} bounded rotation pages; {len(maps)-len(names)} excluded.')


if __name__=='__main__':main()
